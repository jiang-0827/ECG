#ifndef _PROC_HOST_CMD_H_
#define _PROC_HOST_CMD_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
//MODULE_ECG(0x10)模块在骨架阶段新增的二级ID。
//PackUnpack.h里的EnumECGSecondID只定义到0x89，以下取值未与协议层冲突，接心电算法后沿用
#define  DAT_ECG_STS      0x8A      //查询骨架运行状态
#define  CMD_ECG_SET_RATE 0x8B      //设置采样率，arrData[0..1]=采样率(HZ，小端)
#define  CMD_ECG_GET_RATE 0x8C      //查询采样率
#define  CMD_ECG_SET_CH   0x8D      //设置ADC规则通道，arrData[0]=ADC_Channel_x
#define  CMD_ECG_CLR_CNT  0x8E      //清零统计量

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/
//应答消息定义
typedef enum{
  CMD_ACK_OK,           //0 命令成功
  CMD_ACK_CHECKSUM,     //1 校验和错误
  CMD_ACK_LEN,          //2 命令包长度错误
  CMD_ACK_BAD_CMD,      //3 无效命令
  CMD_ACK_PARAM_ERR,    //4 命令参数数据错误
  CMD_ACK_NOT_ACC       //5 命令不接受
}EnumCmdAckType;

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
void  InitProcHostCmd(void);    //初始化ProcHostCmd模块
void  ProcHostCmd(u8 recData);  //处理主机命令

#endif
