/*********************************************************************************************************
* 函数名称：OnWaveSwitch
* 功能功能：波形数据帧上传开关应答处理
* 输入参数：pMsg，命令数据首地址，pMsg[0]为开关(0-停止，1-上传)
* 输出参数：void
* 返 回 值：应答消息
* 生成日期：2026年09月20日
* 注    意：对应MODULE_WAVE + CMD_GEN_WAVE(0x80)，F103里该命令是设置DAC波形
**********************************************************************************************************/
static u8 OnWaveSwitch(u8* pMsg)
{
  if(pMsg[0] > 1)
  {
    return(CMD_ACK_PARAM_ERR);  //参数非法
  }

  SetWaveSendEnable(pMsg[0]);   //设置上传开关

  return(CMD_ACK_OK);           //命令处理成功
}

/*********************************************************************************************************
* 函数名称：OnSetRate
* 功能功能：设置采样率应答处理
* 输入参数：pMsg，pMsg[0]=采样率低字节，pMsg[1]=采样率高字节(HZ，小端)
* 输出参数：void
* 返 回 值：应答消息
* 生成日期：2026年09月20日
* 注    意：
**********************************************************************************************************/
static u8 OnSetRate(u8* pMsg)
{
  u16 rate;

  rate = (u16)pMsg[0] | ((u16)pMsg[1] << 8);  //小端拼成16位

  if((rate == 0) || (rate > 20000))
  {
    return(CMD_ACK_PARAM_ERR);
  }

  SetADCSampleRate(rate);  //设置ADC采样率

  return(CMD_ACK_OK);
}

/*********************************************************************************************************
* 函数名称：OnGetRate
* 功能功能：查询采样率应答处理
* 输入参数：pMsg
* 输出参数：void
* 返 回 值：应答消息
* 生成日期：2026年09月20日
* 注    意：结果同时从printf通道打印一份，方便没有上位机时用串口助手验证
**********************************************************************************************************/
static u8 OnGetRate(u8* pMsg)
{
  printf("ECG sample rate = %d Hz\r\n", GetADCSampleRate());

  return(CMD_ACK_OK);
}

/*********************************************************************************************************
* 函数名称：OnSetChannel
* 功能功能：设置ADC规则通道应答处理
* 输入参数：pMsg，pMsg[0]=ADC_Channel_x(0~18)
* 输出参数：void
* 返 回 值：应答消息
* 生成日期：2026年09月20日
* 注    意：切通道不会改GPIO，若切到别的引脚需自行把该引脚配成模拟输入
**********************************************************************************************************/
static u8 OnSetChannel(u8* pMsg)
{
  if(pMsg[0] > 18)
  {
    return(CMD_ACK_PARAM_ERR);
  }

  SetADCChannel(pMsg[0]);  //切换ADC规则通道

  return(CMD_ACK_OK);
}

/*********************************************************************************************************
* 函数名称：OnGetStatus
* 功能功能：查询骨架运行状态应答处理
* 输入参数：pMsg
* 输出参数：void
* 返 回 值：应答消息
* 生成日期：2026年09月20日
* 注    意：
**********************************************************************************************************/
static u8 OnGetStatus(u8* pMsg)
{
  printf("ECG status: rate=%dHz cnt=%lu drop=%lu queue=%d peak=%d wave=%d\r\n",
          GetADCSampleRate(),
          (unsigned long)GetADCSampleCnt(),
          (unsigned long)GetADCDropCnt(),
          GetADCQueueLen(),
          GetADCQueuePeak(),
          GetWaveSendEnable());

  return(CMD_ACK_OK);
}

/*********************************************************************************************************
* 函数名称：OnClrCount
* 功能功能：清零统计量应答处理
* 输入参数：pMsg
* 输出参数：void
* 返 回 值：应答消息
* 生成日期：2026年09月20日
* 注    意：
**********************************************************************************************************/
static u8 OnClrCount(u8* pMsg)
{
  ClearADCStatic();  //清零采样计数/丢弃计数/队列峰值

  return(CMD_ACK_OK);
}

