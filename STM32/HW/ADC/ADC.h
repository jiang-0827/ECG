#ifndef _ADC_H_
#define _ADC_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "DataType.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/
#define ADC1_BUF_SIZE       256      //缓存环形队列的长度(F103为100)
#define ADC_SAMPLE_RATE_HZ  500      //默认采样率(HZ)，心电监测建议250~1000
#define ADC_VREF_MV         3300     //ADC满量程参考电压(mV)：
                                     //  3300-参考接VDDA；3000-使用板载REF3030精密基准
                                     //  以天空星实际跳线/电阻配置为准，影响的是电压换算精度

/*********************************************************************************************************
*                                              枚举结构体定义
*********************************************************************************************************/

/*********************************************************************************************************
*                                              API函数声明
*********************************************************************************************************/
void  InitADC(void);             //初始化ADC模块

void  SetADCSampleRate(u16 rateHz);  //设置ADC采样率(HZ)，运行中可改
u16   GetADCSampleRate(void);        //获取当前ADC采样率(HZ)
void  SetADCChannel(u8 channel);     //切换ADC规则通道(取值为ADC_Channel_x)

u8    WriteADCBuf(u16 d);        //把ADC数据写入缓冲区
u8    ReadADCBuf(u16 *p);        //从ADC缓冲区读取数据

u16   GetADCQueueLen(void);      //获取当前队列中的点数
u16   GetADCQueuePeak(void);     //获取队列历史最高占用点数(判断是否消费不过来)
u32   GetADCSampleCnt(void);     //获取累计采集点数
u32   GetADCDropCnt(void);       //获取因队列满而丢弃的点数
u32   GetADCOvrCnt(void);        //读取ADC溢出(OVR)次数(诊断,正常应为0)
u32   GetADCDmaCnt(void);        //读取DMA搬运次数(诊断,正常每秒增加约采样率)
u16   GetADCVoltageMv(u16 raw);  //把ADC原始码换算成毫伏
void  ClearADCStatic(void);      //清零统计量(采样计数/丢弃计数/队列峰值)

#endif
