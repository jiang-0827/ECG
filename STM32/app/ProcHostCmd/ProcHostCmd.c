/*********************************************************************************************************
* 函数名称：ProcHostCmd
* 功能功能：处理来自上位机的数据
* 输入参数：recData
* 输出参数：void
* 返 回 值：void
* 生成日期：2018年01月01日
* 注    意：
**********************************************************************************************************/
void ProcHostCmd(u8 recData)
{
  StructPackType pack;    //定义结构体变量
  u8 ack;                 //存储应答消息

  while(UnPackData(recData))   //解析成功
  {
    pack = GetUnPackRslt();    //获取解析结果

    switch(pack.packModuleId)  //模块ID
    {
      case MODULE_WAVE:         //wave模块信息
        switch(pack.packSecondId)
        {
          case CMD_GEN_WAVE:    //波形上传开关
            ack = OnWaveSwitch(pack.arrData);
            break;
          default:
            ack = CMD_ACK_BAD_CMD;
            break;
        }
        SendAckPack(MODULE_WAVE, pack.packSecondId, ack);  //发送命令应答消息
        break;

      case MODULE_ECG:          //心电模块信息
        switch(pack.packSecondId)
        {
          case CMD_ECG_SET_RATE:  //设置采样率
            ack = OnSetRate(pack.arrData);
            break;
          case CMD_ECG_GET_RATE:  //查询采样率
            ack = OnGetRate(pack.arrData);
            break;
          case CMD_ECG_SET_CH:    //设置ADC通道
            ack = OnSetChannel(pack.arrData);
            break;
          case DAT_ECG_STS:       //查询运行状态
            ack = OnGetStatus(pack.arrData);
            break;
          case CMD_ECG_CLR_CNT:   //清零统计量
            ack = OnClrCount(pack.arrData);
            break;
          default:                //其余心电命令(滤波/增益/导联等)等算法接入后再实现
            ack = CMD_ACK_BAD_CMD;
            break;
        }
        SendAckPack(MODULE_ECG, pack.packSecondId, ack);  //发送命令应答消息
        break;

      default:
        break;
    }
  }
}
